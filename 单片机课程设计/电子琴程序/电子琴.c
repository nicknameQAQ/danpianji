//毫秒级延时子程序
void delay1 (uint ms)        
{
 uchar t;
 while (ms--) for (t=0;t<120;t++);
} 
//短暂延时子程序
 void delay(void) 
{ 
 uchar i; 
 for (i=300;i>0;i--); 
} 
//按键扫描子程序
 uchar getkey(void) 
 { 
   uchar scancode,tmpcode;
   if ((P0&0xf0)==0xf0)
      return (0);
   scancode = 0xfe; 
   while((scancode&0x10)!=0)    
   { 						
       P0=scancode;  
       if((P0&0xf0)!=0xf0)  
       { 
         tmpcode = (P0&0xf0)|0x0f;
         return((~scancode)+(~tmpcode));
       } 
       else scancode=(scancode<<1)|0x01;  
   } 
} 
