void senddata(u8,u8);
void delay(u8);

void main()
{
	u8	i,j,k,m,n=0;
	while(1)
	{
	 	for(i=0;i<168;i++)
		{
			for(j=0;j<SPEED;j++)
			{
				for(k=0;k<16;k++)
				{
					m=i+k;
					P1=k;					
					senddata(table1[m],table2[m]);
					delay(70);
				  	senddata(0,0);
				}
			}
		}
	}
  
}

/* 将每行数据送至74HC595	
 * m为高8位,n为低8位
 * SH为移位时钟，ST为锁存时钟 */
void senddata(u8 m,u8 n)
{
	u8 i;
	ST=0;
	for(i=0;i<16;i++)
	{
		SH=0;
		if(i<8)
		  {
		  	DS=0X80&(m<<i);	   
		  }
		else
		  	DS=0X80&(n<<(i-8));
		SH=1;	
	}
	ST=1;
}

void delay(u8 m)
{
	u8 j;
	for(j=m;j>0;j--);
}